#!/usr/bin/env node
/**
 * Reads redirect-map.json, validates every entry, and writes public/_redirects.
 * Fails on: duplicates, self-redirects, cycles, invalid statuses, missing fields,
 * destinations not in scripts/seo-routes.mjs.
 *
 * Format produced is Cloudflare Pages / Netlify _redirects:
 *   <source>  <destination>  <status>
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VALID_DESTINATIONS } from './seo-routes.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const MAP_FILE = path.join(ROOT, 'redirect-map.json');
const OUT_FILE = path.join(ROOT, 'public', '_redirects');
const SITEMAP_FILE = path.join(ROOT, 'public', 'sitemap.xml');

const VALID_STATUSES = new Set([301, 302, 307, 308]);

function fail(msg) {
  console.error(`❌ generate-redirects: ${msg}`);
  process.exit(1);
}

const raw = await fs.readFile(MAP_FILE, 'utf8').catch(() => fail(`missing ${MAP_FILE}`));
let entries;
try { entries = JSON.parse(raw); } catch (e) { fail(`invalid JSON in redirect-map.json: ${e.message}`); }
if (!Array.isArray(entries)) fail('redirect-map.json must be a JSON array');

const errors = [];
const sources = new Map(); // source -> destination
const graph = new Map();   // source -> destination

for (const [i, e] of entries.entries()) {
  const ctx = `entry #${i}`;
  if (!e || typeof e !== 'object') { errors.push(`${ctx}: not an object`); continue; }
  const { source, destination, status } = e;
  if (typeof source !== 'string' || !source.startsWith('/')) errors.push(`${ctx}: invalid source "${source}"`);
  if (typeof destination !== 'string' || !destination.startsWith('/')) errors.push(`${ctx}: invalid destination "${destination}"`);
  if (typeof status !== 'number' || !VALID_STATUSES.has(status)) errors.push(`${ctx}: invalid status ${status}`);
  if (source === destination) errors.push(`${ctx}: self-redirect "${source}"`);
  if (sources.has(source)) errors.push(`${ctx}: duplicate source "${source}"`);
  if (!VALID_DESTINATIONS.has(destination)) errors.push(`${ctx}: destination "${destination}" not in seo-routes VALID_DESTINATIONS`);
  sources.set(source, destination);
  graph.set(source, destination);
}

// Cycle detection (a → b → a, etc.)
for (const start of graph.keys()) {
  let cur = start, hops = 0;
  const visited = new Set([start]);
  while (graph.has(cur)) {
    cur = graph.get(cur);
    if (visited.has(cur)) { errors.push(`cycle detected starting at ${start}`); break; }
    visited.add(cur);
    if (++hops > 10) { errors.push(`redirect chain too long from ${start}`); break; }
  }
}

if (errors.length) {
  for (const e of errors) console.error('  - ' + e);
  fail(`${errors.length} validation error(s)`);
}

// Compose _redirects: canonical-domain rules first, then legacy 301s, then SPA fallback.
const lines = [
  '# AUTO-GENERATED by scripts/generate-redirects.mjs from redirect-map.json',
  '# Do not edit by hand. Edit redirect-map.json and re-run `npm run generate:redirects`.',
  '',
  '# Force non-www to www (Cloudflare Pages canonical)',
  'https://roll-onpainting.com/*  https://www.roll-onpainting.com/:splat  301!',
  'http://roll-onpainting.com/*   https://www.roll-onpainting.com/:splat  301!',
  '',
  '# Static assets — serve directly, never SPA-fallback',
  '/sitemap.xml      /sitemap.xml      200!',
  '/robots.txt       /robots.txt       200!',
  '/llms.txt         /llms.txt         200!',
  '/llms-full.txt    /llms-full.txt    200!',
  '/site.webmanifest /site.webmanifest 200!',
  '',
  `# Legacy 301 redirects (${entries.length} entries from redirect-map.json)`,
];

// Sort for stable output
const sorted = [...entries].sort((a, b) => a.source.localeCompare(b.source));
const pad = (s, n) => s + ' '.repeat(Math.max(1, n - s.length));
for (const { source, destination, status } of sorted) {
  // Cloudflare _redirects requires URL-encoded sources (no raw spaces)
  const safeSource = source.includes(' ') ? source.replace(/ /g, '%20') : source;
  lines.push(`${pad(safeSource, 60)}${pad(destination, 50)}${status}`);
}

lines.push('');

// Force-serve every prerendered route from its own /slug/index.html file.
// Without these explicit 200! rules, Cloudflare Pages can fall through to
// the wildcard SPA fallback below and serve dist/index.html (empty #root)
// instead of the prerendered dist/<slug>/index.html. The 200! status forces
// the rewrite even when the source path has no extension.
try {
  const xml = await fs.readFile(SITEMAP_FILE, 'utf8');
  const locs = [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => m[1].trim());
  const routes = [
    ...new Set(
      locs
        .map((u) => {
          try {
            let p = new URL(u).pathname;
            if (!p.startsWith('/')) p = '/' + p;
            return p === '/' ? '/' : p.replace(/\/+$/, '');
          } catch {
            return null;
          }
        })
        .filter((p) => p && p !== '/')
    ),
  ].sort();
  lines.push(`# Prerendered route overrides (${routes.length} from sitemap.xml) — must come BEFORE SPA fallback`);
  for (const r of routes) {
    lines.push(`${pad(r, 60)}${pad(`${r}/index.html`, 50)}200!`);
  }
  lines.push('');
  console.log(`✓ Added ${routes.length} prerendered-route overrides`);
} catch (e) {
  console.warn(`⚠ could not read sitemap for prerender overrides: ${e.message}`);
}

lines.push('# SPA fallback (last). Pre-rendered /slug/index.html overrides above take priority.');
lines.push('/*    /index.html   200');
lines.push('');

await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });
await fs.writeFile(OUT_FILE, lines.join('\n'), 'utf8');
console.log(`✓ Wrote ${path.relative(ROOT, OUT_FILE)} (${entries.length} legacy redirects + canonical rules)`);